const dialogInputClass =
  'w-full rounded-md border border-zinc-800 bg-zinc-950 px-2.5 py-2 font-mono text-xs text-zinc-100 placeholder-zinc-600 focus:border-emerald-500 focus:outline-none'

export function NewProjectDialog() {
  const open = useWorkspaceStore((s) => s.newProjectOpen)
  const setOpen = useWorkspaceStore((s) => s.setNewProjectOpen)
  const setProject = useWorkspaceStore((s) => s.setProject)
  const createProject = useCreateProject()

  const [name, setName] = useState('')

  const submit = () => {
    const trimmed = name.trim()
    if (!trimmed || createProject.isPending) return
    // No resources: a new project starts empty and they are added from the
    // sidebar (or generated by the AI pane).
    createProject.mutate(
      { name: trimmed },
      {
        onSuccess: (created) => {
          setProject(created.tenantId)
          setOpen(false)
          setName('')
          toast.success(`Provisioned ${created.tenantId}`)
        },
        onError: (e) => toast.error(`Could not create project: ${e.message}`),
      },
    )
  }

  return (
    <Dialog open={open} onOpenChange={setOpen}>
      <DialogContent className="w-80 border-zinc-800 bg-zinc-900 p-4" showCloseButton={false}>
        <DialogTitle className="text-sm font-semibold text-zinc-50">New project</DialogTitle>
        <input
          type="text"
          autoFocus
          placeholder="project-name"
          value={name}
          onChange={(e) => setName(e.target.value)}
          onKeyDown={(e) => {
            if (e.key === 'Enter') submit()
          }}
          className={dialogInputClass}
        />
        <div className="mt-2 flex items-center justify-end gap-2">
          <button
            className="rounded-md px-3 py-1.5 font-mono text-xs text-zinc-400 hover:text-zinc-100"
            onClick={() => setOpen(false)}
          >
            Cancel
          </button>
          <button
            className="rounded-md bg-emerald-500 px-3 py-1.5 font-mono text-xs font-semibold text-black hover:bg-emerald-600 disabled:opacity-60"
            disabled={createProject.isPending}
            onClick={submit}
          >
            {createProject.isPending ? 'Creating…' : 'Create'}
          </button>
        </div>
      </DialogContent>
    </Dialog>
  )
}

/**
 * Deleting deprovisions the tenant on the core and drops the row — there is no
 * undo, so unlike rename this one earns a dialog. It spells out what goes, and
 * Cancel takes focus so a stray Enter cannot confirm it.
 */
function DeleteProjectDialog({
  tenantId,
  name,
  resourceCount,
  open,
  onOpenChange,
}: {
  tenantId: string
  name: string
  resourceCount: number
  open: boolean
  onOpenChange: (open: boolean) => void
}) {
  const deleteProject = useDeleteProject()
  const status = useProjectStatus(tenantId)
  const setStatus = useSetProjectStatus(tenantId)
  const running = status === 'active'

  const stop = useMutation({
    mutationFn: () => setStatus.mutateAsync('stopped'),
    onSuccess: () => toast.success(`${name} stopped — you can delete it now.`),
    onError: (e: Error) => toast.error(`Could not stop ${name}: ${e.message}`),
  })

  const submit = () => {
    if (deleteProject.isPending || running) return
    deleteProject.mutate(tenantId, {
      onSuccess: () => {
        onOpenChange(false)
        toast.success(`Deleted ${name}`)
      },
      onError: (e) => toast.error(`Could not delete ${name}: ${e.message}`),
    })
  }

  return (
    <Dialog open={open} onOpenChange={onOpenChange}>
      <DialogContent className="w-96 border-zinc-800 bg-zinc-900 p-4" showCloseButton={false}>
        <DialogTitle className="text-sm font-semibold text-zinc-50">Delete {name}?</DialogTitle>

        {running ? (
          // The API is serving. Say so plainly and offer the way forward rather
          // than a disabled button with no explanation.
          <div className="flex gap-2.5 rounded-md border border-amber-500/30 bg-amber-500/5 p-3">
            <TriangleAlert className="mt-0.5 h-4 w-4 shrink-0 text-amber-400" />
            <p className="font-mono text-[11px] leading-relaxed text-amber-300">
              This project is running. Deleting it would take a live API down under whatever is
              calling it — stop it first.
            </p>
          </div>
        ) : (
          <p className="font-mono text-xs leading-relaxed text-zinc-400">
            This deletes{' '}
            <span className="text-zinc-200">
              {resourceCount} resource file{resourceCount === 1 ? '' : 's'}
            </span>{' '}
            and its settings, and takes <span className="text-zinc-200">/{tenantId}</span> offline
            for good. It cannot be undone.
          </p>
        )}

        <div className="mt-2 flex items-center justify-end gap-2">
          <button
            autoFocus
            className="rounded-md px-3 py-1.5 font-mono text-xs text-zinc-400 hover:text-zinc-100"
            onClick={() => onOpenChange(false)}
          >
            Cancel
          </button>
          {running ? (
            <button
              className="flex items-center gap-1.5 rounded-md border border-zinc-800 px-3 py-1.5 font-mono text-xs text-zinc-300 transition-colors hover:border-rose-500/40 hover:text-rose-300 disabled:opacity-60"
              disabled={stop.isPending}
              onClick={() => stop.mutate()}
            >
              <Square className="h-3 w-3" />
              {stop.isPending ? 'Stopping…' : 'Stop API'}
            </button>
          ) : (
            <button
              className="flex items-center gap-1.5 rounded-md bg-rose-500 px-3 py-1.5 font-mono text-xs font-semibold text-black transition-colors hover:bg-rose-600 disabled:opacity-60"
              disabled={deleteProject.isPending}
              onClick={submit}
            >
              <Trash2 className="h-3 w-3" />
              {deleteProject.isPending ? 'Deleting…' : 'Delete project'}
            </button>
          )}
        </div>
      </DialogContent>
    </Dialog>
  )
}

/**
 * Renames in place, where the name already is — a one-field dialog is more
 * ceremony than the edit deserves. Enter or clicking away commits, Escape
 * reverts, and the field sizes itself to the text so the bar does not jump.
 */
function InlineRename({
  tenantId,
  initialName,
  onDone,
}: {
  tenantId: string
  initialName: string
  onDone: () => void
}) {
  const [name, setName] = useState(initialName)
  const rename = useRenameProject()
  // Enter commits and then unmounts this field, which can also fire blur.
  // Without this guard that submits the rename twice.
  const settled = useRef(false)

  const commit = () => {
    if (settled.current) return
    const trimmed = name.trim()
    if (!trimmed || trimmed === initialName) {
      settled.current = true
      return onDone()
    }
    settled.current = true
    rename.mutate(
      { tenantId, name: trimmed },
      {
        onSuccess: onDone,
        onError: (e) => {
          toast.error(`Rename failed: ${e.message}`)
          settled.current = false // let them fix it rather than losing the edit
        },
      },
    )
  }

  const cancel = () => {
    settled.current = true
    onDone()
  }

  // The field commits on blur, so a plain click on these buttons would blur
  // first and commit before the click ever landed — cancel could never cancel.
  // Suppressing mousedown keeps focus in the input so only onClick decides.
  const keepFocus = (e: React.MouseEvent) => e.preventDefault()

  return (
    <div className="flex items-center gap-1.5">
      <input
        type="text"
        autoFocus
        value={name}
        disabled={rename.isPending}
        onFocus={(e) => e.currentTarget.select()}
        onChange={(e) => setName(e.target.value)}
        onKeyDown={(e) => {
          if (e.key === 'Enter') commit()
          if (e.key === 'Escape') cancel()
        }}
        onBlur={commit}
        // Sized to the text: a fixed width would make everything beside it jump
        // the moment you start editing.
        style={{ width: `${Math.max(6, name.length + 1)}ch` }}
        className="rounded-none border-b border-emerald-500/60 bg-transparent text-sm font-medium text-zinc-50 focus:outline-none disabled:opacity-60"
      />
      <button
        title="Save"
        aria-label="Save name"
        disabled={rename.isPending}
        onMouseDown={keepFocus}
        onClick={commit}
        className="cursor-pointer text-emerald-500 transition-colors hover:text-emerald-400 disabled:opacity-60"
      >
        <Check className="h-3.5 w-3.5" />
      </button>
      <button
        title="Cancel"
        aria-label="Cancel rename"
        onMouseDown={keepFocus}
        onClick={cancel}
        className="cursor-pointer text-zinc-500 transition-colors hover:text-zinc-200"
      >
        <X className="h-3.5 w-3.5" />
      </button>
    </div>
  )
}

/** Switches the centre pane between the editor, AI chat, logs and diagnostics. */
function ModeToggle() {
  const current = useCurrentProject()
  const status = useProjectStatus(current?.tenantId)
  const stopped = status !== 'active'
  const paneMode = useWorkspaceStore((s) => s.paneMode)
  const setPaneMode = useWorkspaceStore((s) => s.setPaneMode)

  // A stopped API serves no traffic and answers 503 on every public route, so
  // these two panes have nothing to show. Stopping while one of them is open
  // would otherwise strand the user on a dead view — fall back to the editor.
  useEffect(() => {
    if (stopped && (paneMode === 'logs' || paneMode === 'diagnostics')) setPaneMode('editor')
  }, [stopped, paneMode, setPaneMode])

  const modes: { mode: PaneMode; label: string; needsLive?: boolean }[] = [
    { mode: 'editor', label: 'Editor' },
    { mode: 'ai', label: 'AI chat' },
    { mode: 'logs', label: 'Logs', needsLive: true },
    { mode: 'diagnostics', label: 'Diagnostics', needsLive: true },
    // Not needsLive: you manage keys and set up an agent regardless of whether
    // the API is currently serving traffic.
    { mode: 'keys', label: 'API keys' },
  ]

  return (
    <div className="flex items-center gap-1">
      {modes.map(({ mode, label, needsLive }) => {
        // No project reads as "not live" too — with nothing selected there is
        // no traffic to stream and nothing to diagnose.
        const disabled = Boolean(needsLive) && (stopped || !current)
        return (
          <button
            key={mode}
            onClick={() => setPaneMode(mode)}
            disabled={disabled}
            title={disabled ? `Available once the API is live (currently ${status})` : undefined}
            className={
              disabled
                ? 'cursor-not-allowed rounded-md border border-transparent px-2.5 py-1.5 font-mono text-xs text-zinc-700'
                : paneMode === mode
                  ? 'cursor-pointer rounded-md border border-emerald-500/30 bg-emerald-500/10 px-2.5 py-1.5 font-mono text-xs text-emerald-400'
                  : 'cursor-pointer rounded-md border border-transparent px-2.5 py-1.5 font-mono text-xs text-zinc-500 hover:text-zinc-200'
            }
          >
            {label}
          </button>
        )
      })}
    </div>
  )
}

/**
 * Holds a flag true for at least `ms` once it goes up.
 *
 * A deploy against a local core finishes in tens of milliseconds, so progress
 * feedback tied directly to isPending appears and disappears inside a frame or
 * two. That does not read as "it worked", it reads as a glitch.
 */
function useMinDuration(active: boolean, ms = 450): boolean {
  const [visible, setVisible] = useState(false)
  const startedAt = useRef(0)

  useEffect(() => {
    if (active) {
      startedAt.current = Date.now()
      setVisible(true)
      return
    }
    if (!visible) return
    const remaining = Math.max(0, ms - (Date.now() - startedAt.current))
    const timer = setTimeout(() => setVisible(false), remaining)
    return () => clearTimeout(timer)
  }, [active, visible, ms])

  return visible
}

/**
 * One control for publishing and for start/stop.
 *
 * Deploy is the primary action and stays clickable in every state: it promotes
 * staged drafts, and doing that while the API is already live is the common
 * case, so it cannot be swapped out for a Stop button. The start/stop toggle
 * therefore hangs off the same button as a menu rather than sitting beside it
 * — one control, both actions, and the destructive one is a deliberate second
 * click instead of a thing you hit by accident next to Deploy.
 */
function DeployControls({ tenantId }: { tenantId: string | undefined }) {
  const status = useProjectStatus(tenantId)
  const setStatus = useSetProjectStatus(tenantId)
  const stopped = status !== 'active'

  const deploy = useMutation({
    mutationFn: async () => {
      const res = await deployProject(tenantId!)
      // Deploying a stopped project brings it back up — one action, one click.
      if (stopped) await setStatus.mutateAsync('active')
      return res
    },
    onSuccess: (res) => {
      const files =
        res.promoted.length > 0
          ? `${res.promoted.length} file${res.promoted.length === 1 ? '' : 's'}: ${res.promoted.join(', ')}`
          : 'no draft changes'
      toast.success(stopped ? `API is live again (${files})` : `Deployed ${files}`)
    },
    onError: (e) => toast.error(`Deploy failed: ${e.message}`),
  })

  const toggleStatus = useMutation({
    mutationFn: () => setStatus.mutateAsync(stopped ? 'active' : 'stopped'),
    onSuccess: () =>
      toast.success(
        stopped ? 'API started — endpoints are serving again.' : 'API stopped — requests now answer 503.',
      ),
    onError: (e: Error) => toast.error(`Could not change status: ${e.message}`),
  })

  // Held briefly so fast round-trips still register as a state, not a flicker.
  const deploying = useMinDuration(deploy.isPending)
  const busy = deploying || deploy.isPending || toggleStatus.isPending

  return (
    <div className="flex items-stretch">
      <button
        onClick={() => deploy.mutate()}
        disabled={!tenantId || busy}
        className="flex cursor-pointer items-center gap-1.5 rounded-l-md bg-emerald-500 px-3 py-1.5 font-mono text-xs font-semibold text-black transition-colors hover:bg-emerald-600 disabled:opacity-60"
      >
        {/* Progress lives on the icon, not the label. Swapping the word to
            "Deploying…" and back inside ~50ms stutters; the word only changes
            when the API's state actually changes, which is worth reading. */}
        {deploying ? (
          <Loader2 className="h-3.5 w-3.5 shrink-0 animate-spin" />
        ) : (
          <Rocket className="h-3.5 w-3.5 shrink-0" />
        )}
        {/* Live already means published, so the action is a re-publish; while
            stopped the same button also brings the API back up, which reads as
            a plain Deploy.

            Fixed 8ch — the width of "Redeploy", exact because the font is
            monospace. Without it the button resizes with its label, and being
            in the right-aligned group it drags the mode toggle sideways. */}
        {/* With no project there is nothing deployed, so "Redeploy" would be a
            lie on the very first screen a new account sees. */}
        <span className="w-[8ch] text-center">{stopped || !tenantId ? 'Deploy' : 'Redeploy'}</span>
      </button>
      <DropdownMenu>
        <DropdownMenuTrigger asChild>
          <button
            title="More actions"
            disabled={!tenantId || busy}
            className="flex cursor-pointer items-center rounded-r-md border-l border-black/20 bg-emerald-500 px-1.5 text-black transition-colors hover:bg-emerald-600 disabled:opacity-60"
          >
            <ChevronDown className="h-3.5 w-3.5" />
          </button>
        </DropdownMenuTrigger>
        <DropdownMenuContent align="end" className="w-44 border-zinc-800 bg-zinc-900 p-1.5">
          <DropdownMenuItem
            onSelect={() => toggleStatus.mutate()}
            className={`flex cursor-pointer items-center gap-2 rounded-md px-2 py-1.5 font-mono text-xs ${
              stopped ? 'text-emerald-400' : 'text-rose-300'
            }`}
          >
            {stopped ? <Play className="h-3 w-3" /> : <Square className="h-3 w-3" />}
            {toggleStatus.isPending
              ? stopped
                ? 'Starting…'
                : 'Stopping…'
              : stopped
                ? 'Start API'
                : 'Stop API'}
          </DropdownMenuItem>
        </DropdownMenuContent>
      </DropdownMenu>
    </div>
  )
}

/** Whether this project's API is serving — shown beside its name. */
function StatusBadge({ tenantId }: { tenantId: string }) {
  const status = useProjectStatus(tenantId)
  const stopped = status !== 'active'
  return (
    <span
      title={stopped ? 'Public endpoints answer 503' : 'Public endpoints are serving'}
      className="flex shrink-0 items-center gap-1.5 font-mono text-xs text-zinc-500"
    >
      <span className={`h-1.5 w-1.5 rounded-full ${stopped ? 'bg-zinc-600' : 'bg-emerald-500'}`} />
      {stopped ? status : 'live'}
    </span>
  )
}

export function TopBar() {
  const { data: projects, isLoading } = useProjects()
  const current = useCurrentProject()
  const setProject = useWorkspaceStore((s) => s.setProject)
  const setNewProjectOpen = useWorkspaceStore((s) => s.setNewProjectOpen)
  const user = useAuthStore((s) => s.user)
  const logout = useAuthStore((s) => s.logout)
  const [renaming, setRenaming] = useState(false)
  const [menuOpen, setMenuOpen] = useState(false)
  // Which project the confirm dialog is about — any row in the list, not just
  // the one currently open.
  const [deleteTarget, setDeleteTarget] = useState<Project | null>(null)

  return (
    <div className="flex h-14 shrink-0 items-center gap-2.5 border-b border-zinc-800 bg-zinc-950 px-5">
      <img src="/stubbase-logo-text.png" alt="Stubbase" className="h-5 w-auto" />
      <ChevronRight className="h-3.5 w-3.5 text-zinc-700" />
      {/* `group` so the rename pencil can reveal on hover of the whole block. */}
      <div className="group flex items-center gap-2">
        {current && renaming ? (
          <InlineRename
            tenantId={current.tenantId}
            initialName={current.name}
            onDone={() => setRenaming(false)}
          />
        ) : (
        <DropdownMenu open={menuOpen} onOpenChange={setMenuOpen}>
          <DropdownMenuTrigger asChild>
            <button className="flex cursor-pointer items-center gap-1 text-sm font-medium text-zinc-50 select-none">
              {current?.name ?? (isLoading ? 'Loading…' : 'No project')}
            </button>
          </DropdownMenuTrigger>
          <DropdownMenuContent align="start" className="w-56 border-zinc-800 bg-zinc-900 p-1.5">
            <DropdownMenuLabel className="px-2 py-1 text-[10px] font-semibold tracking-wide text-zinc-600 uppercase">
              Projects
            </DropdownMenuLabel>
            {(projects ?? []).map((p) => (
              <DropdownMenuItem
                key={p.tenantId}
                onSelect={() => setProject(p.tenantId)}
                className={`flex cursor-pointer items-center gap-2 rounded-md px-2 py-1.5 ${
                  p.tenantId === current?.tenantId ? 'bg-zinc-800/80' : ''
                }`}
              >
                <div
                  className={`flex h-5 w-5 shrink-0 items-center justify-center rounded ${p.color} text-[10px] font-bold text-black`}
                >
                  {p.name[0]?.toUpperCase()}
                </div>
                <span
                  className={`flex-1 truncate font-mono text-xs ${
                    p.tenantId === current?.tenantId ? 'text-zinc-100' : 'text-zinc-300'
                  }`}
                >
                  {p.name}
                </span>
                {p.tenantId === current?.tenantId && (
                  <Check className="h-3 w-3 shrink-0 text-emerald-500" />
                )}
                <button
                  title={`Delete ${p.name}`}
                  aria-label={`Delete ${p.name}`}
                  /* The row selects on pointer-up, so a bare onClick here would
                     switch to the project as well as open the dialog. Swallow
                     the pointer events and drive it from onClick alone. */
                  onPointerDown={(e) => e.stopPropagation()}
                  onPointerUp={(e) => e.stopPropagation()}
                  onClick={(e) => {
                    e.stopPropagation()
                    e.preventDefault()
                    setMenuOpen(false) // get the menu out of the dialog's way
                    setDeleteTarget(p)
                  }}
                  /* Always visible, unlike the rename pencil: the menu is an
                     explicit surface you had to open, so the action should be
                     findable without hunting for it by hovering. */
                  className="shrink-0 cursor-pointer text-zinc-700 transition-colors hover:text-rose-400"
                >
                  <Trash2 className="h-3 w-3" />
                </button>
              </DropdownMenuItem>
            ))}
            <DropdownMenuSeparator className="my-1 bg-zinc-800" />
            <DropdownMenuItem
              onSelect={() => setNewProjectOpen(true)}
              className="flex cursor-pointer items-center gap-2 rounded-md px-2 py-1.5 text-zinc-400 hover:text-zinc-100"
            >
              <div className="flex h-5 w-5 shrink-0 items-center justify-center rounded border border-dashed border-zinc-600">
                <Plus className="h-3 w-3" />
              </div>
              <span className="font-mono text-xs">New project</span>
            </DropdownMenuItem>
          </DropdownMenuContent>
        </DropdownMenu>
        )}
        {current && !renaming && (
          <button
            title="Rename project"
            aria-label="Rename project"
            onClick={() => setRenaming(true)}
            /* Hidden until the name is hovered (or the button is keyboard
               focused). Opacity rather than display, so revealing it never
               shifts the status badge sitting next to it. */
            className="cursor-pointer text-zinc-600 opacity-0 transition-opacity group-hover:opacity-100 hover:text-zinc-200 focus-visible:opacity-100"
          >
            <Pencil className="h-3 w-3" />
          </button>
        )}
        {/* Hidden while renaming: the save/cancel pair is the only thing that
            should be competing for attention in that moment. */}
        {current && !renaming && <StatusBadge tenantId={current.tenantId} />}
      </div>

      <NewProjectDialog />
      {deleteTarget && (
        <DeleteProjectDialog
          key={deleteTarget.tenantId}
          tenantId={deleteTarget.tenantId}
          name={deleteTarget.name}
          resourceCount={deleteTarget.resources.length}
          open
          onOpenChange={(open) => !open && setDeleteTarget(null)}
        />
      )}

      <span className="flex-1" />
      <ModeToggle />
      <DeployControls tenantId={current?.tenantId} />
      <button
        title={`Log out${user ? ` (${user.email})` : ''}`}
        onClick={logout}
        className="flex h-7 w-7 cursor-pointer items-center justify-center rounded-md text-zinc-500 transition-colors hover:bg-zinc-900 hover:text-zinc-100"
      >
        <LogOut className="h-3.5 w-3.5" />
      </button>
    </div>
  )
}
